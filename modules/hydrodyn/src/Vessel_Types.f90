subroutine Vessel_UnPackParam(RF, OutData)
   type(RegFile), intent(inout)    :: RF
   type(Vessel_ParameterType), intent(inout) :: OutData
   character(*), parameter            :: RoutineName = 'Vessel_UnPackParam'
   integer(B4Ki)   :: i1, i2
   integer(B4Ki)   :: LB(2), UB(2)
   integer(IntKi)  :: stat
   logical         :: IsAllocAssoc
   integer(B8Ki)   :: PtrIdx
   type(c_ptr)     :: Ptr
   if (RF%ErrStat /= ErrID_None) return
   call RegUnpack(RF, OutData%BodyID); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%DT); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%FrameSpd); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%RhoW); if (RegCheckErr(RF, RoutineName)) return
   if (associated(OutData%WaveField)) deallocate(OutData%WaveField)
   call RegUnpack(RF, IsAllocAssoc); if (RegCheckErr(RF, RoutineName)) return
   if (IsAllocAssoc) then
      call RegUnpackPointer(RF, Ptr, PtrIdx); if (RegCheckErr(RF, RoutineName)) return
      if (c_associated(Ptr)) then
         call c_f_pointer(Ptr, OutData%WaveField)
      else
         allocate(OutData%WaveField,stat=stat)
         if (stat /= 0) then 
            call SetErrStat(ErrID_Fatal, 'Error allocating OutData%WaveField.', RF%ErrStat, RF%ErrMsg, RoutineName)
            return
         end if
         RF%Pointers(PtrIdx) = c_loc(OutData%WaveField)
         call SeaSt_WaveField_UnpackSeaSt_WaveFieldType(RF, OutData%WaveField) ! WaveField 
      end if
   else
      OutData%WaveField => null()
   end if
   call RegUnpack(RF, OutData%HasWaves); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%HullRef); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%Lpp); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%Breadth); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%Draft); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%zH); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%UMin); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%ResMod); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%R0); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpackAlloc(RF, OutData%ResU); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpackAlloc(RF, OutData%ResR); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%XDer); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%YDer); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%NDer); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%mx); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%my); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpack(RF, OutData%NProp); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpackAlloc(RF, OutData%PropPos); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpackAlloc(RF, OutData%PropD); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpackAlloc(RF, OutData%tP); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpackAlloc(RF, OutData%wP0); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpackAlloc(RF, OutData%C1); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpackAlloc(RF, OutData%C2Pos); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpackAlloc(RF, OutData%C2Neg); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpackAlloc(RF, OutData%ThrShr); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpackAlloc(RF, OutData%PropOWMod); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpackAlloc(RF, OutData%KTPoly); if (RegCheckErr(RF, RoutineName)) return
   call RegUnpackAlloc(RF, OutData%KQPoly); if (RegCheckErr(RF, RoutineName)) return
   if (allocated(OutData%OWTbl)) deallocate(OutData%OWTbl)
   call RegUnpack(RF, IsAllocAssoc); if (RegCheckErr(RF, RoutineName)) return
   if (IsAllocAssoc) then
      call RegUnpackBounds(RF, 1, LB, UB); if (RegCheckErr(RF, RoutineName)) return
      allocate(OutData%OWTbl(LB(1):UB(1)),stat=stat)
      if (stat /= 0) then 
         call SetErrStat(ErrID_Fatal, 'Error allocating OutData%OWTbl.', RF%ErrStat, RF%ErrMsg, RoutineName)
         return
      end if
